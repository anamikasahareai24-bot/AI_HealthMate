def get_parameter_explanation(parameter_name, language="English"):
    """
    Returns a simple explanation for a medical parameter.
    """

    parameter_key = parameter_name.strip().lower()

    explanation = PARAMETER_EXPLANATIONS.get(parameter_key)

    if not explanation:
        return "Explanation for this parameter is currently unavailable."

    return explanation.get(
        language,
        explanation["English"]
    )